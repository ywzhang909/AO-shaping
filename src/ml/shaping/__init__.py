"""Inverse beam shaping: far-field spot -> SLM pupil phase.

A physics-informed U-Net for the *inverse* direction of the AO-shaping bench.
Where :mod:`ml.zernike` learns the **forward** map (commanded pupil phase ->
measured far field), this package learns the **inverse** map (far-field spot ->
commanded pupil phase), which is what a shaping loop actually needs: give it the
spot you want, get back the phase to display.

============================  What the supervision is  ============================

The hardware corpus in :mod:`ml.hwdataset` is **forward-only**. There is no
target-spot -> phase supervision anywhere in the repository. Two facts follow,
and they determine the whole design:

1. The map is **many-to-one**. A global piston offset, and more generally any
   phase whose phasor differs from another by a spatial constant, produces an
   identical far-field intensity. A network trained on the physics term alone
   therefore has an unconstrained direction and can only ever learn a
   conditional mean.
2. The far field **loses information** the SLM needs.

So the objective anchors on **both**:

.. code-block:: text

    L = w_sup * L1(pred_phasor, gt_phasor)          # real hardware pairs
      + w_phy * L1(forward(pred_phase), image)      # closed through the bench
      + w_smooth * TV(pred_phasor)                  # off by default (see config)

``L_sup`` pins the specific phase that was actually commanded (and breaks the
piston degeneracy); ``L_phy`` requires that phase to be *physically realisable*
on this bench. Neither alone is sufficient -- see :mod:`ml.shaping.losses`.

============================  Why the physics leg is calibrated  ============================

A naive ``fft2`` propagator is **wrong on this bench by a factor of ~4 in angular
scale**. The measured ``far_field_padding`` sweep on 128 real samples gives R2 of
-0.20 at padding 1, -0.12 at 4, +0.33 at 8, +0.46 at 10, +0.53 at 12, +0.49 at
16 and +0.18 at 20 -- an interior optimum that tracks the family's ``fov_px``.
:mod:`ml.shaping.physics` therefore takes its padding **only** from
:func:`~ml.zernike.models.recommended_padding`; there is no literal padding
anywhere in this package.

============================  A measured warning  ============================

The repository has already established, over 14 independent attempts recorded in
``report/loss_defects/PROCESS.md``, that **forward-model accuracy does not
predict inverse-design ability**, and that the binding constraint is the
*training distribution* (the corpus holds the mild aberrations of four
optimisation objectives) rather than model capacity. It has also measured that
Gerchberg-Saxton **alone** never beats a flat phase (negative in 90/90 runs), and
that synthetic "strong phase" augmentation generated by the repo's own
propagator is not independent information (correlation 0.9956 with the model it
is meant to supplement).

This package is built *despite* those results, not because they were overlooked:
the corpus contains **real** measured pairs that no synthetic generator can
reproduce, which is exactly the kind of information the 2026-10 audit concluded
was missing. But a reader should expect the physics term to be the one that
carries the generalisation, and should judge it on **file-paired** statistics
with the corpus noise floor (val R2 spans 0.748-0.937 on the *same* config under
split-seed changes alone) quoted alongside every number.

============================  Multi-family caveat  ============================

``report/hwdataset_corpus/report.md`` records that the corpus's 7 families are
**perfectly collinear** with their phase representation (``source`` and family
are the same variable), and forbids reading a cross-family comparison as a claim
about representation quality. This package trains across families by explicit
user decision, using each family's own calibrated padding, and mitigates the
red line rather than pretending it is absent: per-family metrics are reported
separately, records with no usable padding are excluded from the physics term
with an explicit count rather than silently dropped, and no cross-family
aggregate is presented as a representation claim.
"""

from __future__ import annotations

__all__ = [
    "ShapingConfig",
]


def __getattr__(name: str) -> object:
    """Resolve the public API lazily.

    Submodules pull in ``torch`` and the corpus index; importing them eagerly
    would make ``import ml.shaping`` pay for the optional ``ml`` dependency
    group and would break the cheap ``from ml.shaping.config import ShapingConfig``
    path used by the CLI's parser tests.

    Args:
        name: Attribute being looked up on the package.

    Returns:
        The resolved attribute.

    Raises:
        AttributeError: If ``name`` is not part of this package's public API.
    """
    if name == "ShapingConfig":
        from ml.shaping.config import ShapingConfig

        return ShapingConfig
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")